import { expect, test } from '@playwright/test'

async function signIn(page: import('@playwright/test').Page) {
  await page.goto('/login?returnTo=/tracks')
  await page.getByLabel('Имя пользователя').fill('fixture_user')
  await page.getByLabel('Пароль').fill('fixture password long')
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page).toHaveURL(/\/tracks$/)
  await expect(page.getByRole('contentinfo').getByRole('button', { name: 'Открыть очередь, 3 из 100', exact: true })).toBeVisible()
}

test('queue drawer supports reorder, occurrence playback, remove and confirmed clear', async ({ page }) => {
  await signIn(page)
  const footer = page.getByRole('contentinfo'), audio = page.locator('audio')
  await expect(footer.getByRole('button', { name: /Открыть очередь/ })).toHaveCount(1)
  await footer.getByRole('button', { name: /Открыть очередь/ }).click()
  const panel = page.getByRole('region', { name: 'Очередь воспроизведения' })
  await expect(panel.getByText('3 / 100 треков')).toBeVisible()
  await panel.getByRole('button', { name: 'Выше: 3. Track 2 — Artist 2' }).click()
  await expect(panel.getByText('3 / 100 треков')).toBeVisible()
  await panel.getByRole('button', { name: 'Закрыть' }).click()

  const add = page.waitForResponse((response) => response.url().endsWith('/api/queue') && response.request().method() === 'PUT')
  await page.getByRole('main').getByRole('button', { name: 'Добавить в очередь: Track 4' }).click()
  expect((await add).status()).toBe(200)
  await footer.getByRole('button', { name: /Открыть очередь/ }).click()
  await expect(panel.getByText('4 / 100 треков')).toBeVisible()
  await panel.getByRole('button', { name: 'Играть: 4. Track 4 — Artist 4' }).click()
  await expect(panel.getByRole('listitem', { name: '4. Track 4 — Artist 4' })).toHaveAttribute('aria-current', 'true')
  await expect(audio).toHaveAttribute('src', /track-4\.mp3$/)
  await expect.poll(() => audio.evaluate((node: HTMLAudioElement) => !node.paused)).toBe(true)
  await panel.getByRole('button', { name: 'Закрыть' }).click()
  await expect(footer.getByText('4 / 4', { exact: true })).toBeVisible()
  await footer.getByRole('button', { name: /Открыть очередь/ }).click()
  await panel.getByRole('button', { name: 'Убрать: 4. Track 4 — Artist 4' }).click()
  await expect(panel.getByText('3 / 100 треков')).toBeVisible()
  await panel.getByRole('button', { name: 'Очистить', exact: true }).click()
  const confirm = page.getByRole('dialog', { name: 'Очистить очередь?' })
  await confirm.getByRole('button', { name: 'Очистить', exact: true }).click()
  await expect(panel).toBeHidden()
  await footer.getByRole('button', { name: /Открыть очередь/ }).click()
  await expect(panel.getByText('Очередь пуста. Добавьте треки из каталога.')).toBeVisible()
  await expect.poll(() => audio.evaluate((node: HTMLAudioElement) => node.paused)).toBe(true)
})

test('bulk selection adds entries and confirms replacement of a nonempty queue', async ({ page }) => {
  await signIn(page)
  await page.getByRole('main').getByRole('checkbox', { name: 'Выбрать Track 5' }).check()
  await page.getByRole('main').getByRole('checkbox', { name: 'Выбрать Track 6' }).check()
  const append = page.waitForResponse((response) => response.url().endsWith('/api/queue') && response.request().method() === 'PUT')
  await page.getByRole('main').getByRole('button', { name: 'Добавить выбранные' }).click()
  const appended = await append
  expect(appended.status()).toBe(200)
  expect((await appended.request().postDataJSON()).entries).toHaveLength(5)

  await page.getByRole('main').getByRole('checkbox', { name: 'Выбрать Track 7' }).check()
  const replace = page.waitForResponse((response) => response.url().endsWith('/api/queue') && response.request().method() === 'PUT')
  await page.getByRole('main').getByRole('button', { name: 'Заменить выбранными' }).click()
  await page.getByRole('dialog', { name: 'Заменить выбранными' }).getByRole('button', { name: 'Заменить выбранными' }).click()
  const replaced = await replace
  expect(replaced.status()).toBe(200)
  expect((await replaced.request().postDataJSON()).entries).toHaveLength(1)
  await page.getByRole('contentinfo').getByRole('button', { name: /Открыть очередь/ }).click()
  await expect(page.getByRole('region', { name: 'Очередь воспроизведения' }).getByText('1 / 100 треков')).toBeVisible()
})

test('replacement confirmation traps keyboard focus, cancels with Escape and restores the trigger', async ({ page }) => {
  await signIn(page)
  const main = page.getByRole('main')
  await main.getByRole('checkbox', { name: 'Выбрать Track 5', exact: true }).check()
  const trigger = main.getByRole('button', { name: 'Заменить выбранными', exact: true })
  let writes = 0
  page.on('request', request => { if (request.url().endsWith('/api/queue') && request.method() === 'PUT') writes++ })
  await trigger.focus()
  await trigger.press('Enter')
  const dialog = page.getByRole('dialog', { name: 'Заменить выбранными' })
  const cancel = dialog.getByRole('button', { name: 'Отмена', exact: true })
  const confirm = dialog.getByRole('button', { name: 'Заменить выбранными', exact: true })
  await expect(cancel).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(confirm).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(cancel).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(trigger).toBeFocused()
  expect(writes).toBe(0)
  await trigger.press('Enter')
  await expect(cancel).toBeFocused()
  await page.keyboard.press('Tab')
  await page.keyboard.press('Enter')
  await expect(dialog).toBeHidden()
  await expect(main.getByRole('status')).toHaveText('Очередь обновлена.')
  expect(writes).toBe(1)
})

test('shows failed additions beside their row and confirms successful additions', async ({ page }) => {
  await signIn(page)
  await page.route('**/api/queue', async route => {
    if (route.request().method() === 'PUT') await route.fulfill({ status: 503, json: {} })
    else await route.continue()
  })
  const main = page.getByRole('main')
  const button = main.getByRole('button', { name: 'Добавить в очередь: Track 4', exact: true })
  const row = main.locator('.MuiCard-root').filter({ has: page.getByRole('button', { name: 'Добавить в очередь: Track 4', exact: true }) })
  await button.click()
  await expect(row.getByRole('alert')).toBeVisible()
  await expect(row.getByRole('status')).toHaveCount(0)
  await page.unroute('**/api/queue')
  await page.getByRole('contentinfo').getByRole('button', { name: /Открыть очередь/ }).click()
  const panel = page.getByRole('region', { name: 'Очередь воспроизведения' })
  await panel.getByRole('button', { name: 'Повторить сохранение', exact: true }).click()
  await expect(panel.getByText('4 / 100 треков')).toBeVisible()
  await panel.getByRole('button', { name: 'Закрыть', exact: true }).click()
  await expect(row.getByRole('alert')).toHaveCount(0)
  const added = main.getByRole('button', { name: 'Добавить в очередь: Track 5', exact: true })
  await added.click()
  await expect(main.locator('.MuiCard-root').filter({ has: page.getByRole('button', { name: 'Добавить в очередь: Track 5', exact: true }) }).getByRole('status')).toHaveText('Трек добавлен в очередь.')
})

test('refuses a stale replacement confirmation after another tab changes the queue', async ({ page, context }) => {
  await signIn(page)
  const other = await context.newPage()
  await other.goto('/tracks')
  await expect(other.getByRole('contentinfo').getByRole('button', { name: 'Открыть очередь, 3 из 100', exact: true })).toBeVisible()
  const main = page.getByRole('main')
  await main.getByRole('checkbox', { name: 'Выбрать Track 5', exact: true }).check()
  await main.getByRole('button', { name: 'Заменить выбранными', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Заменить выбранными' })
  await other.getByRole('main').getByRole('button', { name: 'Добавить в очередь: Track 4', exact: true }).click()
  await expect(dialog).toContainText('4 вхождений')
  let writes = 0
  page.on('request', request => { if (request.url().endsWith('/api/queue') && request.method() === 'PUT') writes++ })
  await dialog.getByRole('button', { name: 'Заменить выбранными', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('Очередь изменилась')
  expect(writes).toBe(0)
  await dialog.getByRole('button', { name: 'Отмена', exact: true }).click()
  await page.getByRole('contentinfo').getByRole('button', { name: /Открыть очередь/ }).click()
  await expect(page.getByRole('region', { name: 'Очередь воспроизведения' }).getByText('4 / 100 треков')).toBeVisible()
})

