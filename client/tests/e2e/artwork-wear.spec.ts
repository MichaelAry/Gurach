import { expect, test } from '@playwright/test'

test('guest cover wears from actual playback, retains its marks, and can be reset', async ({ page }, info) => {
  await page.goto('/tracks')
  await page.getByRole('button', { name: 'Играть Track 1', exact: true }).click()
  await page.getByRole('button', { name: 'Открыть полноэкранный плеер' }).click()
  const copy = page.getByRole('region', { name: 'Моя копия' })
  const marks = page.locator('[data-wear-level]')
  await expect(copy.getByRole('status')).toHaveText('Моя копия · Без износа')
  const audio = page.locator('audio')
  await expect.poll(() => audio.evaluate((node: HTMLAudioElement) => !node.paused)).toBe(true)
  await audio.evaluate((node: HTMLAudioElement) => { node.playbackRate = 4 })
  await expect(marks).toHaveAttribute('data-wear-level', '1', { timeout: 15_000 })
  await page.getByRole('button', { name: 'Пауза', exact: true }).click()
  const pattern = await marks.getAttribute('style')
  await page.screenshot({ path: info.outputPath('wear-desktop.png') })

  await copy.getByRole('button', { name: 'Моя копия' }).focus()
  await page.keyboard.press('Tab')
  await expect(copy.getByRole('button', { name: 'Оригинал' })).toHaveCSS('outline-style', 'solid')
  await page.keyboard.press('Enter')
  await expect(marks).toHaveCount(0)
  await page.screenshot({ path: info.outputPath('original-desktop.png') })
  await copy.getByRole('button', { name: 'Моя копия' }).click()
  await expect(marks).toHaveAttribute('style', pattern!)
  await page.reload()
  await expect(marks).toHaveAttribute('style', pattern!)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 568 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await expect(marks).toHaveCSS('animation-name', 'none')
  await page.screenshot({ path: info.outputPath('wear-mobile.png'), fullPage: true })

  await copy.getByRole('button', { name: 'Сбросить износ' }).click()
  await expect(copy.getByRole('status')).toHaveText('Моя копия · Без износа')
  await expect(marks).toHaveCount(0)
  await page.reload()
  await expect(copy.getByRole('status')).toHaveText('Моя копия · Без износа')
  await page.getByRole('slider', { name: 'Позиция воспроизведения' }).press('Home')
  await page.getByRole('button', { name: 'Играть', exact: true }).click()
  await expect.poll(() => audio.evaluate((node: HTMLAudioElement) => !node.paused)).toBe(true)
  await audio.evaluate((node: HTMLAudioElement) => { node.playbackRate = 4 })
  await expect(marks).toHaveAttribute('style', pattern!, { timeout: 15_000 })
})
