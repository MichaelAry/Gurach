import { expect, test } from '@playwright/test'
test('restarts duplicate occurrences and commits current removal/clear through the account queue', async ({ page }) => {
  await page.goto('/login')
  await page.getByLabel('Имя пользователя').fill('fixture_user')
  await page.getByLabel('Пароль').fill('fixture password long')
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page).toHaveURL(/\/tracks$/)
  const footer = page.getByRole('contentinfo'), audio = page.locator('audio')
  let listenRequests = 0
  page.on('request', (request) => { if (new URL(request.url()).pathname === '/api/account/listens') listenRequests++ })
  await expect(audio).toHaveCount(1)
  await page.getByRole('button', { name: 'Играть Track 1', exact: true }).click()
  await expect(footer.getByText('1 / 3', { exact: true })).toBeVisible()
  await expect.poll(() => audio.evaluate((node: HTMLAudioElement) => !node.paused)).toBe(true)
  expect(listenRequests).toBe(0)
  await audio.evaluate((node: HTMLAudioElement) => { node.playbackRate = 4 })
  await expect.poll(() => listenRequests, { timeout: 10_000 }).toBe(1)
  await audio.evaluate((node: HTMLAudioElement) => { node.currentTime = 5 })
  const duplicateLoaded = audio.evaluate((node: HTMLAudioElement) => new Promise<void>((resolve) => node.addEventListener('loadedmetadata', () => resolve(), { once: true })))
  await footer.getByRole('button', { name: 'Следующий', exact: true }).click()
  await expect(footer.getByText('2 / 3', { exact: true })).toBeVisible()
  await duplicateLoaded
  await expect.poll(() => audio.evaluate((node: HTMLAudioElement) => node.readyState >= 2 && !node.paused)).toBe(true)
  await audio.evaluate((node: HTMLAudioElement) => { node.playbackRate = 4 })
  await expect.poll(() => listenRequests, { timeout: 10_000 }).toBe(2)
  await audio.evaluate((node: HTMLAudioElement) => { node.playbackRate = 0.25 })
  await footer.getByRole('button', { name: /Открыть очередь/ }).click()
  const queue = page.getByRole('region', { name: 'Очередь воспроизведения' })
  await queue.getByRole('button', { name: 'Выше: 3. Track 2 — Artist 2' }).click()
  await queue.getByRole('button', { name: 'Закрыть' }).click()
  await expect(footer.getByText('3 / 3', { exact: true })).toBeVisible()
  await expect.poll(() => audio.evaluate((node: HTMLAudioElement) => !node.paused)).toBe(true)
  expect(listenRequests).toBe(2)
  await expect(audio).toHaveAttribute('src', /track-1\.mp3$/)
  await footer.getByRole('button', { name: /Открыть очередь/ }).click()
  await queue.getByRole('button', { name: 'Убрать: 3. Track 1 — Artist 1' }).click()
  await queue.getByRole('button', { name: 'Закрыть' }).click()
  await expect(footer.getByText('2 / 2', { exact: true })).toBeVisible()
  await expect(audio).toHaveAttribute('src', /track-2\.mp3$/)
  await footer.getByRole('button', { name: /Открыть очередь/ }).click()
  await queue.getByRole('button', { name: 'Очистить', exact: true }).click()
  await page.getByRole('dialog', { name: 'Очистить очередь?' }).getByRole('button', { name: 'Очистить', exact: true }).click()
  await expect(audio).not.toHaveAttribute('src')
  await expect.poll(() => audio.evaluate((node: HTMLAudioElement) => node.paused)).toBe(true)
})
