import { expect, test } from '@playwright/test'

test('seeds fifty automatic tracks and keeps manual additions in FIFO order before the random remainder', async ({ page }) => {
  await page.goto('/tracks')
  await expect(page.getByRole('button', { name: 'Добавить в очередь: Track 5', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Играть Track 1', exact: true }).click()
  await page.getByRole('button', { name: 'Добавить в очередь: Track 5', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Добавить в очередь: Track 6', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Добавить в очередь: Track 6', exact: true }).click()
  const footer = page.getByRole('contentinfo')
  await footer.getByRole('button', { name: /Открыть очередь/ }).click()
  const panel = page.getByRole('region', { name: 'Очередь воспроизведения' })
  await expect(panel.getByText('52 / 100 треков')).toBeVisible()
  const rows = panel.getByRole('listitem')
  await expect(rows.nth(0)).toHaveAttribute('aria-label', '1. Track 1 — Artist 1')
  await expect(rows.nth(1)).toHaveAttribute('aria-label', '2. Track 5 — Artist 5')
  await expect(rows.nth(2)).toHaveAttribute('aria-label', '3. Track 6 — Artist 6')
  await expect(rows.nth(3)).toHaveAttribute('aria-label', '4. Track 2 — Artist 2')
  await expect(panel.getByText('Добавлен вручную', { exact: true })).toHaveCount(2)
  await page.reload()
  await footer.getByRole('button', { name: /Открыть очередь/ }).click()
  await expect(panel.getByText('52 / 100 треков')).toBeVisible()
  await expect(rows.nth(1)).toHaveAttribute('aria-label', '2. Track 5 — Artist 5')
  await panel.getByRole('button', { name: 'Очистить', exact: true }).click()
  await page.getByRole('dialog', { name: 'Очистить очередь?' }).getByRole('button', { name: 'Очистить', exact: true }).click()
  await page.reload()
  await footer.getByRole('button', { name: /Открыть очередь/ }).click()
  await expect(panel.getByText('Очередь пуста. Добавьте треки из каталога.')).toBeVisible()
})

test('persists guest queue across reload, restores paused and imports by an explicit account choice', async ({ page }) => {
  await page.goto('/tracks')
  await expect(page.getByRole('button', { name: 'Играть Track 1', exact: true })).toBeVisible()
  const footer = page.getByRole('contentinfo'), audio = page.locator('audio')
  await page.getByRole('button', { name: 'Добавить в очередь: Track 1', exact: true }).click()
  await page.getByRole('button', { name: 'Играть Track 1', exact: true }).click()
  await expect(footer.getByText('1 / 51', { exact: true })).toBeVisible()
  await expect.poll(() => audio.evaluate((node: HTMLAudioElement) => !node.paused)).toBe(true)
  await page.reload()
  await expect(page.getByRole('button', { name: 'Играть Track 1', exact: true })).toBeVisible()
  await expect(footer.getByText('1 / 51', { exact: true })).toBeVisible()
  await expect(audio).toHaveAttribute('src', /track-1\.mp3$/)
  await expect.poll(() => audio.evaluate((node: HTMLAudioElement) => node.paused)).toBe(true)

  await page.goto('/login?returnTo=/tracks')
  await page.getByLabel('Имя пользователя').fill('fixture_user')
  await page.getByLabel('Пароль').fill('fixture password long')
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page).toHaveURL(/\/tracks$/)
  const dialog = page.getByRole('dialog', { name: 'Гостевая очередь' })
  await expect(dialog).toBeVisible()
  const write = page.waitForResponse((response) => response.url().endsWith('/api/queue') && response.request().method() === 'PUT')
  await dialog.getByRole('button', { name: 'Объединить выбранные' }).click()
  const saved = await write
  expect(saved.status()).toBe(200)
  expect((await saved.request().postDataJSON()).entries).toHaveLength(4)
  await expect(dialog).toBeHidden()
  const guest = await page.evaluate(() => JSON.parse(localStorage.getItem('gurach:guest-queue') ?? 'null'))
  expect(guest.snapshot.entries).toHaveLength(51)
  await page.reload()
  await expect(page.getByRole('dialog', { name: 'Гостевая очередь' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Выйти', exact: true }).click()
  await expect(page).toHaveURL(/\/tracks$/)
  await expect(page.getByRole('contentinfo').getByText('1 / 51', { exact: true })).toBeVisible()
})

test('synchronizes guest queue across tabs but gives audio playback to only one tab', async ({ page, context }) => {
  await page.goto('/tracks')
  await expect(page.getByRole('button', { name: 'Играть Track 1', exact: true })).toBeVisible()
  const second = await context.newPage()
  await second.goto('/tracks')
  await expect(second.getByRole('button', { name: 'Играть Track 1', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Играть Track 1', exact: true }).click()
  const secondFooter = second.getByRole('contentinfo')
  await secondFooter.getByRole('button', { name: /Открыть очередь/ }).click()
  const secondQueue = second.getByRole('region', { name: 'Очередь воспроизведения' })
  await expect(secondQueue.getByText('50 / 100 треков')).toBeVisible()
  await secondQueue.getByRole('button', { name: 'Закрыть' }).click()
  await expect.poll(() => page.locator('audio').evaluate((node: HTMLAudioElement) => !node.paused)).toBe(true)
  await second.getByRole('button', { name: 'Играть Track 1', exact: true }).click()
  await expect(second.getByText('Плеер уже работает в другой вкладке. Остановите его там и повторите запуск.')).toBeVisible()
  await expect.poll(() => second.locator('audio').evaluate((node: HTMLAudioElement) => node.paused)).toBe(true)
  await expect.poll(() => page.locator('audio').evaluate((node: HTMLAudioElement) => !node.paused)).toBe(true)
})

test('quarantines invalid guest data and offers a reset without breaking the catalogue', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('gurach:guest-queue', JSON.stringify({ version: 99, snapshot: {} })))
  await page.goto('/tracks')
  await expect(page.getByRole('button', { name: 'Играть Track 1', exact: true })).toBeVisible()
  const warning = page.getByText(/Сохранённая гостевая очередь повреждена/)
  await expect(warning).toBeVisible()
  const quarantined = await page.evaluate(() => localStorage.getItem('gurach:guest-queue:invalid'))
  expect(quarantined).toContain('"version":99')
  await page.getByRole('button', { name: 'Сбросить гостевую очередь' }).click()
  await expect(warning).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Играть Track 1', exact: true })).toBeVisible()
})

test('falls back to a visible per-tab in-memory queue when browser storage writes fail', async ({ page }) => {
  await page.addInitScript(() => {
    const original = Storage.prototype.setItem
    Storage.prototype.setItem = function (key, value) {
      if (key === 'gurach:guest-queue') throw new DOMException('Quota exceeded', 'QuotaExceededError')
      original.call(this, key, value)
    }
  })
  await page.goto('/tracks')
  await page.getByRole('button', { name: 'Играть Track 1', exact: true }).click()
  await expect(page.getByRole('contentinfo').getByText('1 / 50', { exact: true })).toBeVisible()
  await expect(page.getByText(/Гостевая очередь хранится только в этой вкладке/)).toBeVisible()
  await expect.poll(() => page.locator('audio').evaluate((node: HTMLAudioElement) => !node.paused)).toBe(true)
})

test('keeps guest and account queues separate across account A and B', async ({ page }) => {
  await page.goto('/tracks')
  await page.getByRole('button', { name: 'Добавить в очередь: Track 20', exact: true }).click()
  await page.getByRole('button', { name: 'Играть Track 20', exact: true }).click()
  await expect(page.getByRole('contentinfo').getByText('1 / 51', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Войти' }).first().click()
  await expect(page).toHaveURL(/\/login/)
  await page.getByLabel('Имя пользователя').fill('fixture_user')
  await page.getByLabel('Пароль').fill('fixture password long')
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  let dialog = page.getByRole('dialog', { name: 'Гостевая очередь' })
  await expect(dialog).toBeVisible()
  const replace = page.waitForResponse((response) => response.url().endsWith('/api/queue') && response.request().method() === 'PUT')
  await dialog.getByRole('button', { name: 'Заменить выбранными' }).click()
  expect((await replace).status()).toBe(200)
  await page.getByRole('button', { name: 'Выйти', exact: true }).click()
  await expect(page.getByRole('contentinfo').getByText('1 / 51', { exact: true })).toBeVisible()

  await page.getByRole('link', { name: 'Войти' }).first().click()
  await expect(page).toHaveURL(/\/login/)
  await page.getByLabel('Имя пользователя').fill('fixture_other')
  await page.getByLabel('Пароль').fill('fixture password long')
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  dialog = page.getByRole('dialog', { name: 'Гостевая очередь' })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByText('В очереди аккаунта: 3/100.')).toBeVisible()
  await dialog.getByRole('button', { name: 'Оставить очередь аккаунта' }).click()
  await expect(dialog).toBeHidden()
  const guest = await page.evaluate(() => JSON.parse(localStorage.getItem('gurach:guest-queue') ?? 'null'))
  expect(guest.snapshot.entries).toHaveLength(51)
  expect(guest.snapshot.entries[0].trackId).toBe((20).toString(16).padStart(24, '0'))
})
