import { expect, test } from '@playwright/test'

test('saves favorites across reloads and synchronizes track, player, and favorites page', async ({ page }) => {
  const id = '000000000000000000000001'
  await page.goto('/login?returnTo=/tracks')
  await page.getByLabel('Имя пользователя').fill('fixture_user')
  await page.getByLabel('Пароль').fill('fixture password long')
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  const add = page.getByRole('button', { name: 'Добавить в избранное: Track 1', exact: true })
  await expect(add).toBeEnabled()
  await add.click()
  await expect(page.getByRole('main').getByRole('button', { name: 'Убрать из избранного: Track 1', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.reload()
  await expect(page.getByRole('main').getByRole('button', { name: 'Убрать из избранного: Track 1', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Играть Track 1', exact: true }).click()
  await expect(page.getByRole('contentinfo').getByRole('button', { name: 'Убрать из избранного: Track 1', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.goto(`/tracks/${id}`)
  await expect(page.getByRole('main').getByRole('button', { name: 'Убрать из избранного: Track 1', exact: true })).toBeEnabled()
  await page.goto('/favorites')
  await expect(page.getByRole('link', { name: 'Track 1', exact: true })).toBeVisible()
  await page.getByRole('main').getByRole('button', { name: 'Убрать из избранного: Track 1', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Track 1', exact: true })).toHaveCount(0)
  await expect(page.getByText(/В избранном пока нет треков/)).toBeVisible()
  await page.reload()
  await expect(page.getByText(/В избранном пока нет треков/)).toBeVisible()
})

test('offers login to guests and preserves state when saving fails', async ({ page }) => {
  await page.goto('/tracks')
  await page.getByRole('button', { name: 'Войти, чтобы добавить в избранное: Track 2', exact: true }).click()
  await expect(page).toHaveURL(/\/login\?returnTo=%2Ftracks$/)
  await page.getByLabel('Имя пользователя').fill('fixture_other')
  await page.getByLabel('Пароль').fill('fixture password long')
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await page.route('**/api/account/favorites/*', (route) => route.fulfill({ status: 503, body: '{}' }))
  const button = page.getByRole('button', { name: 'Добавить в избранное: Track 2', exact: true })
  await button.click()
  await expect(page.getByText('Не удалось изменить избранное. Попробуйте ещё раз.')).toBeVisible()
  await expect(button).toHaveAttribute('aria-pressed', 'false')
  await expect(button).toBeEnabled()
})
